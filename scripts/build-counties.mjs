// Writes src/data/counties.ts: Taiwan's county and city outlines (Ministry of
// the Interior boundaries via the taiwan-atlas package, 政府資料開放授權條款),
// simplified to about a kilometre, so the app can tell which city's TDX or
// open-data feed covers a point. Islets smaller than a few hundred metres are
// left out; those points fall back to the rough boxes in taiwan.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";

const CODES = {
  臺北市: "Taipei",
  新北市: "NewTaipei",
  基隆市: "Keelung",
  桃園市: "Taoyuan",
  新竹市: "Hsinchu",
  新竹縣: "HsinchuCounty",
  苗栗縣: "MiaoliCounty",
  臺中市: "Taichung",
  彰化縣: "ChanghuaCounty",
  南投縣: "NantouCounty",
  雲林縣: "YunlinCounty",
  嘉義市: "Chiayi",
  嘉義縣: "ChiayiCounty",
  臺南市: "Tainan",
  高雄市: "Kaohsiung",
  屏東縣: "PingtungCounty",
  宜蘭縣: "YilanCounty",
  花蓮縣: "HualienCounty",
  臺東縣: "TaitungCounty",
  澎湖縣: "PenghuCounty",
  金門縣: "KinmenCounty",
  連江縣: "LienchiangCounty",
};
const TOLERANCE = 0.006; // degrees, about 600 m
const MIN_SIZE = 0.004; // rings smaller than this across are dropped

const pkg = new URL("../node_modules/taiwan-atlas/", import.meta.url);
const { version } = JSON.parse(readFileSync(new URL("package.json", pkg)));
const topo = JSON.parse(readFileSync(new URL("counties-10t.json", pkg)));
const geo = feature(topo, topo.objects.counties);

/** Douglas–Peucker on an open polyline. */
function simplify(points, tol) {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points.at(-1);
  const dx = bx - ax;
  const dy = by - ay;
  const len = Math.hypot(dx, dy);
  let far = 0;
  let at = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const d = len ? Math.abs(dy * px - dx * py + bx * ay - by * ax) / len : Math.hypot(px - ax, py - ay);
    if (d > far) [far, at] = [d, i];
  }
  if (far <= tol) return [points[0], points.at(-1)];
  return [...simplify(points.slice(0, at + 1), tol).slice(0, -1), ...simplify(points.slice(at), tol)];
}

function ring(points) {
  const xs = points.map((p) => p[0]);
  const ys = points.map((p) => p[1]);
  if (Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) < MIN_SIZE) return null;
  // Split the closed ring in two so the far point of each half is kept.
  const half = Math.floor(points.length / 2);
  const out = [...simplify(points.slice(0, half + 1), TOLERANCE).slice(0, -1), ...simplify(points.slice(half), TOLERANCE)];
  return out.length >= 4 ? out.slice(0, -1).flatMap(([x, y]) => [Math.round(x * 1000) / 1000, Math.round(y * 1000) / 1000]) : null;
}

const shapes = {};
for (const f of geo.features) {
  // The source writes 台 where the TDX names use 臺.
  const code = CODES[f.properties.COUNTYNAME.replace(/^台/, "臺")];
  if (!code) throw new Error(`unknown county ${f.properties.COUNTYNAME}`);
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  // Every ring, holes included (Chiayi City sits inside Chiayi County): even-odd tests handle both.
  shapes[code] = polys.flatMap((p) => p.map(ring)).filter(Boolean);
}
const missing = Object.values(CODES).filter((c) => !shapes[c]?.length);
if (missing.length) throw new Error(`no outline for ${missing.join(", ")}`);

const body = Object.entries(shapes)
  .map(([code, rings]) => `  ${code}: [\n${rings.map((r) => `    [${r.join(",")}],`).join("\n")}\n  ],`)
  .join("\n");
writeFileSync(
  new URL("../src/data/counties.ts", import.meta.url),
  `// Generated by scripts/build-counties.mjs from taiwan-atlas ${version} (Ministry of the Interior
// county boundaries, 政府資料開放授權條款第 1 版). Do not edit; run \`node scripts/build-counties.mjs\`.
// Each ring is a flat [lng, lat, lng, lat, …] list, simplified to about ${Math.round(TOLERANCE * 100)} km.

export const COUNTY_SHAPES: Record<string, number[][]> = {
${body}
};
`,
);
const vertices = Object.values(shapes).flat().reduce((n, r) => n + r.length / 2, 0);
console.log(`counties.ts: ${Object.keys(shapes).length} counties, ${Object.values(shapes).flat().length} rings, ${vertices} vertices`);
